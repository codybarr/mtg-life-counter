// Generates src/ui/icons.generated.ts from @tabler/icons node data, keeping
// only the icons the app uses so the full icon set never enters the bundle.
const NAMES = [
  'minus', 'plus', 'settings', 'crown', 'building-castle', 'droplet', 'skull',
  'bolt', 'star', 'radioactive', 'cloud-storm', 'hash', 'sword', 'coins',
  'dice-5', 'refresh', 'users', 'layout-grid', 'heart', 'x', 'bulb', 'pencil',
  'palette', 'users-group', 'check', 'heart-broken',
] as const

const nodes: Record<string, Array<[string, Record<string, string>]>> =
  await Bun.file('node_modules/@tabler/icons/tabler-nodes-outline.json').json()

const picked = Object.fromEntries(
  NAMES.map(name => {
    const icon = nodes[name]
    if (!icon) throw new Error(`Unknown Tabler icon: ${name}`)
    return [name, icon]
  }),
)

const source = `// Generated by scripts/icons.ts — do not edit by hand.
export const ICON_NODES = ${JSON.stringify(picked, null, 2)} as const satisfies Record<string, ReadonlyArray<readonly [string, Readonly<Record<string, string>>]>>

export type IconName = keyof typeof ICON_NODES
`
await Bun.write('src/ui/icons.generated.ts', source)
console.log(`Wrote ${NAMES.length} icons`)
